let lang = localStorage['jizura.lang'] === 'ja' ? 'ja' : 'en';

const t = key => I18N[lang][key] ?? I18N.en[key] ?? key;
const tName = o => (lang === 'en' && o.nameEn) ? o.nameEn : o.name;
const tDesc = o => (lang === 'en' && o.descEn) ? o.descEn : o.desc;
const i18nKeys = () => Object.keys(I18N.en);

const applyStatic = () => {
  document.documentElement.lang = lang;
  const sel = document.getElementById('langSelect');
  if (sel) sel.value = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
};

const setLang = l => {
  lang = l;
  localStorage['jizura.lang'] = l;
  applyStatic();
  document.dispatchEvent(new CustomEvent('jizura:lang', { detail: { lang } }));
};

window.JI = { t, tName, tDesc, setLang, applyStatic, i18nKeys, get lang() { return lang; } };

const init = () => {
  applyStatic();
  const sel = document.getElementById('langSelect');
  if (sel) sel.addEventListener('change', () => setLang(sel.value));
};
if (document.body) init();
else document.addEventListener('DOMContentLoaded', init);
