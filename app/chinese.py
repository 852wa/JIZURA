def replace_copy(source, glossary):
    # One pass, longest key first. Japanese and Chinese share kanji, so a translation can itself contain a
    # shorter Japanese key (透明 inside 透明 PNG, 背景 inside 背景切換…); a single pass never re-translates the output.
    keys = sorted(glossary, key=len, reverse=True)
    pattern = re.compile('|'.join(re.escape(key) for key in keys))
    return pattern.sub(lambda match: glossary[match.group(0)], source)


def localize_body(source):
    return replace_copy(source, BODY)


def localize_js(source, filename):
    if filename.endswith('12_ui.js'):
        return replace_copy(source, UI)
    if filename.endswith('11_export.js'):
        return replace_copy(source, EXPORT)
    return source
